#!/bin/bash

# =============================================================================
# tmux カスタム結合レイアウト作成スクリプト (Alt+4)
# =============================================================================
#
# Alt+3の学習から得た知識を活用した実装
#
# 目標レイアウト:
# ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
# │         │    ?    │    ?    │         │    ?    │    ?    │
# │    1    ├─────────┼─────────┤    ?    ├─────────┴─────────┤
# │         │    ?    │    ?    │         │                   │
# └─────────┴─────────┴─────────┴─────────┴───────────────────┘
#
# 特徴: 右端の2つのペイン（上部の2つ）が下部で結合される
#
# =============================================================================

create_custom_merged_layout() {
  # 冪等性チェック
  if [ $(tmux list-panes | wc -l) -gt 1 ]; then
    tmux display-message "Layout already applied"
    return
  fi

  # ステップ1: 横に6分割（Alt+3と同じ）
  # 結果: 1,2,3,4,5,6
  tmux split-window -h -c "#{pane_current_path}" # ペイン2作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン3作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン4作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン5作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン6作成

  # 均等配置に調整（Alt+3を踏襲）
  tmux select-layout even-horizontal

  # ステップ2: ペイン2を上下分割（Alt+3と同じ）
  # 結果: 1,2,3,4,5,6,7 (元の3→4, 元の4→5, 元の5→6, 元の6→7)
  tmux select-pane -t 2
  tmux split-window -v -c "#{pane_current_path}"

  # ステップ3: ペイン4（元のペイン3）を上下分割（Alt+3と同じ）
  # 結果: 1,2,3,4,5,6,7,8 (元の5→6, 元の6→7, 元の7→8)
  tmux select-pane -t 4
  tmux split-window -v -c "#{pane_current_path}"

  # 現在の状態（Alt+3のステップ3完了時点）:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │         │    2    │    4    │         │         │         │
  # │    1    ├─────────┼─────────┤    6    │    7    │    8    │
  # │         │    3    │    5    │         │         │         │
  # └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘

  # ステップ4: ペイン8を削除して結合効果を実現（Alt+3から変更）
  # ────────────────────────────────────────────────────────────
  # 【重要】Alt+3ではここでペイン8を上下分割するが、今回は削除して結合効果を得る
  #
  # 分割前: 1,2,3,4,5,6,7,8
  # ペイン8を削除すると、ペイン7が自動的に右端2列分の幅に拡張される
  # 分割後: 1,2,3,4,5,6,7 (ペイン8が削除され、7が拡張)
  #
  tmux kill-pane -t 8

  # 現在の状態:
  # ┌─────────┬─────────┬─────────┬─────────┬───────────────────┐
  # │         │    2    │    4    │         │                   │
  # │    1    ├─────────┼─────────┤    6    │         7         │
  # │         │    3    │    5    │         │                   │
  # └─────────┴─────────┴─────────┴─────────┴───────────────────┘

  # ステップ5: ペイン7（現在の右端）を上下分割
  # ────────────────────────────────────────────────────────────
  # 分割前: 1,2,3,4,5,6,7
  # ペイン7を上下分割すると、新しいペイン8が下側に作成される
  # 分割後: 1,2,3,4,5,6,7,8
  #
  tmux select-pane -t 7
  tmux split-window -v -c "#{pane_current_path}"

  # 現在の状態:
  # ┌─────────┬─────────┬─────────┬─────────┬───────────────────┐
  # │         │    2    │    4    │         │         7         │
  # │    1    ├─────────┼─────────┤    6    ├───────────────────┤
  # │         │    3    │    5    │         │         8         │
  # └─────────┴─────────┴─────────┴─────────┴───────────────────┘

  # ステップ6: ペイン7（右端上部）を左右分割
  # ────────────────────────────────────────────────────────────
  # 分割前: 1,2,3,4,5,6,7,8
  # ペイン7を左右分割すると、新しいペイン8が右側に作成され、
  # 元のペイン8以降が全て+1される
  # 分割後: 1,2,3,4,5,6,7,8,9 (元の8→9)
  #
  tmux select-pane -t 7
  tmux split-window -h -c "#{pane_current_path}"

  # 最終状態（目標レイアウト完成）:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │         │    2    │    4    │         │    7    │    8    │
  # │    1    ├─────────┼─────────┤    6    ├─────────┴─────────┤
  # │         │    3    │    5    │         │         9         │
  # └─────────┴─────────┴─────────┴─────────┴───────────────────┘

  # ステップ7は不要（すでに目標レイアウト達成）
  # ────────────────────────────────────────────────────────────
  # ステップ6で目標レイアウトが完成しているため、追加の結合は不要

  # フォーカスを最初のペインに戻す（Alt+3を踏襲）
  tmux select-pane -t 1

  echo "Custom merged layout created successfully"
}

# メイン実行
create_custom_merged_layout
