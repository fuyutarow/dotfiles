#!/bin/bash

# =============================================================================
# tmux 6分割混合レイアウト作成スクリプト (Alt+3)
# =============================================================================
#
# 【教材】tmuxのペイン分割における番号変化の重要な学習例
#
# このスクリプトは、tmuxでカスタムレイアウトを作成する際の
# **ペイン番号の動的変化**を理解するための教材として作成されました。
#
# 目標レイアウト:
# ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
# │         │    2    │    4    │         │         │    8    │
# │    1    ├─────────┼─────────┤    6    │    7    ├─────────┤
# │         │    3    │    5    │         │         │    9    │
# └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘
#
# =============================================================================
# 【重要概念】ペイン番号の動的変化
# =============================================================================
#
# tmuxでペインを分割すると、既存のペイン番号が動的に変化します。
# これを理解せずにスクリプトを書くと、意図しないペインを操作してしまいます。
#
# 基本ルール:
# 1. 新しいペインが作成されると、それ以降の番号が全て+1される
# 2. split-window -v (上下分割): 現在のペインの下に新ペインが作成される
# 3. split-window -h (左右分割): 現在のペインの右に新ペインが作成される
# 4. 番号は作成順ではなく、画面上の位置で動的に振り直される
#
# =============================================================================
# 【詳細解説】処理ステップとペイン番号変化
# =============================================================================

create_6pane_mixed_layout() {
  # 既にペインが複数ある場合は処理をスキップ（冪等性保証）
  if [ $(tmux list-panes | wc -l) -gt 1 ]; then
    tmux display-message "Layout already applied"
    return
  fi

  # ステップ1: 横に6分割
  # ────────────────────────────────────────────────────────────
  # 目的: まず基本となる6つの縦列を作成
  # 結果: ペイン1,2,3,4,5,6 (左から右へ均等配置)
  #
  tmux split-window -h -c "#{pane_current_path}" # ペイン2作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン3作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン4作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン5作成
  tmux split-window -h -c "#{pane_current_path}" # ペイン6作成

  # 均等配置に調整（重要：これにより全ペインが同じ幅になる）
  tmux select-layout even-horizontal

  # 現在の状態:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │    1    │    2    │    3    │    4    │    5    │    6    │
  # └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘

  # ステップ2: ペイン2を上下分割
  # ────────────────────────────────────────────────────────────
  # 【重要】ここでペイン番号が変化します！
  #
  # 分割前: 1,2,3,4,5,6
  # ペイン2を上下分割すると、新しいペイン3が下側に作成され、
  # 元のペイン3以降が全て+1されます
  # 分割後: 1,2,3,4,5,6,7 (元の3→4, 元の4→5, 元の5→6, 元の6→7)
  #
  tmux select-pane -t 2
  tmux split-window -v -c "#{pane_current_path}"

  # 現在の状態:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │         │    2    │         │         │         │         │
  # │    1    ├─────────┤    4    │    5    │    6    │    7    │
  # │         │    3    │         │         │         │         │
  # └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘

  # ステップ3: ペイン4（元のペイン3）を上下分割
  # ────────────────────────────────────────────────────────────
  # 【重要】再びペイン番号が変化します！
  #
  # 分割前: 1,2,3,4,5,6,7
  # ペイン4を上下分割すると、新しいペイン5が下側に作成され、
  # 元のペイン5以降が全て+1されます
  # 分割後: 1,2,3,4,5,6,7,8 (元の5→6, 元の6→7, 元の7→8)
  #
  tmux select-pane -t 4
  tmux split-window -v -c "#{pane_current_path}"

  # 現在の状態:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │         │    2    │    4    │         │         │         │
  # │    1    ├─────────┼─────────┤    6    │    7    │    8    │
  # │         │    3    │    5    │         │         │         │
  # └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘

  # ステップ4: ペイン8（元のペイン6）を上下分割
  # ────────────────────────────────────────────────────────────
  # 【重要】最後のペイン番号変化
  #
  # 分割前: 1,2,3,4,5,6,7,8
  # ペイン8を上下分割すると、新しいペイン9が下側に作成されます
  # このケースでは8が最後のペインなので、それ以降のペインは存在せず、
  # 番号変化は8→8（上側）、9（下側、新規作成）のみです
  # 分割後: 1,2,3,4,5,6,7,8,9
  #
  tmux select-pane -t 8
  tmux split-window -v -c "#{pane_current_path}"

  # 最終状態（目標レイアウト完成）:
  # ┌─────────┬─────────┬─────────┬─────────┬─────────┬─────────┐
  # │         │    2    │    4    │         │         │    8    │
  # │    1    ├─────────┼─────────┤    6    │    7    ├─────────┤
  # │         │    3    │    5    │         │         │    9    │
  # └─────────┴─────────┴─────────┴─────────┴─────────┴─────────┘

  # フォーカスを最初のペインに戻す
  tmux select-pane -t 1

  echo "6-pane mixed layout created successfully"
}

# =============================================================================
# 【学習ポイント】後続のLLMへのメッセージ
# =============================================================================
#
# 1. **ペイン番号は固定ではない**: 新しいペインが作成されるたびに動的に変化
#
# 2. **番号変化のパターン**:
#    - 分割されるペインより後ろの番号が全て+1される
#    - 上下分割: 下側に新ペイン、左右分割: 右側に新ペイン
#
# 3. **デバッグ方法**:
#    - 各ステップ後に `tmux list-panes -F '#{pane_index}'` で確認
#    - `tmux display-panes` で視覚的に番号を確認
#
# 4. **スクリプト設計時の注意**:
#    - 分割順序を慎重に計画する
#    - 各ステップでどのペイン番号が変化するかを予測する
#    - テスト環境で実際の番号変化を確認する
#
# 5. **冪等性の重要性**:
#    - 既にレイアウトが適用済みかチェックする
#    - 重複実行を防ぐ仕組みを実装する
#
# このスクリプトは、tmuxの複雑なペイン操作における
# 実践的な学習教材として活用してください。
#
# =============================================================================

# メイン実行
create_6pane_mixed_layout
